export function toggleLocale() {
    const nextLocale = i18n.global.locale.value === 'zh-CN' ? 'en-US' : 'zh-CN';
    i18n.global.locale.value = nextLocale;
    localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale);
}
